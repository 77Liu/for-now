import { sessionSerial } from "../../session/index.mjs";
import { publishDomains, state } from "../../state/index.mjs";

export function installPrimaryDescriptors(descriptors, ports) {
  const {
    runtime,runtimeFeatureLoaders,$,actionsCoordinator,showToast,request,
    featureRequestV1,withFeatureScope,mediaDraftStore,requestCoordinator,refreshState,
    applyPendingProjection,resetOccurrenceInput,occurrenceFields,imageDataUrls,
    viewerAttachmentPath,requestStream,apiClient,contentImageDraft,
    activateContentImageDraft,renderContentImageEditor,resetContentImageEditor,
    persistContentImageDraft,contentImagePaths,clearSubmittedContentImageDraft,
    discardContentImageUploads,setContentImageFiles,contentImagesMarkup,
    markCommentTarget,applyCommentAnchors,scheduleAnnotationLineCounts,
    commentRootKey,openThoughtDetail,promoteCaptureToThought,
    scheduleNotificationPoll,runAnswerInModal,appUrl,contentState,
    contextReceiptMarkup,renderLatex,trapHomeEditorFocus,pageAudioCoordinator,
    startupPerformanceEnabled,encodeAudioDraft,readAudioDraftDuration,
    runPublicValidation,discardUploadedImagePath,dataUrlFromBlob,
    normalizedFeedSearch,feedSearchEmpty,splitTags,formatBytes,dailyTypeMeta,
    setOccurrenceMode,uncertainMediaSubmission,blankCanvas,loadImageSource,
    tagCommentableTargets,openCommentPanel,openHomeEditor,
    checkinsFeatureControllers,thoughtsFeatureControllers,pageRouter,
    createHomeFeatureController,escapeHtml,plainPreview,
    presentError,renderMarkdown,uploadOriginalImages,validatedImageFiles,
    createUnavailableRouteResult,entryKeyIntent,eventDate,eventTimestamp,
    formatDate,formatDateKey,formatTime,localDateKey,localDateTimeForDate,
    toLocalDateTimeInput
  } = ports;
  const withCheckins=async delegate=>{
    const module=await runtimeFeatureLoaders.checkins();
    const controller=module.createCheckinsFeatureController({delegate,getSnapshot:()=>state,getActiveDate:()=>runtime.activeDate,document,emptyStateMarkup:contentState});
    checkinsFeatureControllers.add(controller);return controller
  };
  descriptors.today={
    root:()=>$("#view-today"),
    load:()=>withCheckins(createHomeFeatureController({
      coordinator:actionsCoordinator,
      loadWorkspace:runtimeFeatureLoaders.actions,
      canLoad:()=>Boolean(runtime.currentUser?.id),
      showToast,
      prompt:(...args)=>globalThis.prompt(...args),
      confirm:(...args)=>globalThis.confirm(...args)
    }))
  };
  descriptors.daily={
    root:()=>$("#view-daily"),
    load:()=>runtimeFeatureLoaders.health().then(health=>{
      const controller=health.createHealthFeatureController({
        request,
        requestV1:(url,options,coordination)=>featureRequestV1("daily",url,options,coordination),
        draftStore:mediaDraftStore,
        listOperations:owner=>requestCoordinator.list(owner),
        subscribeOperations:listener=>requestCoordinator.subscribe(listener),
        getAccountId:()=>runtime.currentUser?.id||"",
        getActiveDate:()=>runtime.activeDate,
        getActiveType:()=>runtime.activeDailyType,
        setActiveType:type=>{runtime.activeDailyType=type},
        getRecords:()=>state.dailyRecords||[],
        replaceRecord:(id,record)=>{
          state.dailyRecords=(state.dailyRecords||[]).map(item=>item.id===id?record:item)
        },
        applyPendingRecord:applyPendingProjection,
        refreshRecords:()=>refreshState("dailyRecords"),
        resetOccurrenceInput,
        occurrenceFields,
        imageDataUrls,
        escapeMarkup:escapeHtml,
        viewerAttachmentPath,
        localDateTimeForDate,
        toLocalDateTimeInput,
        showToast,
        confirmDelete:message=>confirm(message),
        typeMeta:dailyTypeMeta,
        createId:()=>crypto.randomUUID()
      });
      runtime.healthFeatureController=controller;
      return controller
    })
  };
  const loadCaptureJournalPage=viewName=>runtimeFeatureLoaders.captureJournal().then(module=>{
    const controller=module.createCaptureJournalFeatureController({
      page:viewName,
      data:{
        getSnapshot:()=>state,
        getAccountId:()=>runtime.currentUser?.id||"",
        getSessionSerial:()=>sessionSerial,
        request,
        requestV1:(url,options,coordination)=>featureRequestV1(viewName,url,options,coordination),
        requestStream,
        requestBlob:(url,options,config)=>apiClient.requestBlob(url,options,config),
        refresh:(domains,options)=>refreshState(domains,options),
        applyPendingProjection,
        publish:domains=>publishDomains(new Set(domains))
      },
      navigation:{openThoughtDetail},
      media:{
        snapshot:contentImageDraft,
        activateDraft:key=>activateContentImageDraft(key,runtime.currentUser?.id),
        renderEditor:renderContentImageEditor,
        resetEditor:resetContentImageEditor,
        replaceTransient:(key,snapshot)=>runtime.contentImageDraftManager.replaceTransient(key,snapshot),
        persistDraft:persistContentImageDraft,
        submitDraft:contentImagePaths,
        completeDraft:clearSubmittedContentImageDraft,
        rollbackDraft:discardContentImageUploads,
        selectFiles:setContentImageFiles,
        removeItem:(key,index)=>runtime.contentImageDraftManager.remove(key,index),
        contentImagesMarkup
      },
      drafts:{storage:sessionStorage,getAccountId:()=>runtime.currentUser?.id||""},
      annotations:{
        markTarget:markCommentTarget,
        applyAnchors:applyCommentAnchors,
        scheduleLayout:scheduleAnnotationLineCounts,
        rootKey:commentRootKey
      },
      crossDomain:{promoteToThought:promoteCaptureToThought,scheduleNotificationPoll},
      assistant:{runAnswer:runAnswerInModal},
      view:{
        appUrl,
        contentState,
        contextReceiptMarkup,
        renderLatex,
        showToast,
        presentError,
        resetOccurrenceInput,
        occurrenceFields,
        trapFocus:trapHomeEditorFocus,
        escapeMarkup:escapeHtml,
        entryKeyIntent
      },
      platform:{
        document,
        window,
        audio:pageAudioCoordinator,
        draftStore:mediaDraftStore,
        createRequestId:()=>crypto.randomUUID(),
        requestFrame:callback=>requestAnimationFrame(callback),
        setTimer:(callback,delay)=>setTimeout(callback,delay),
        clearTimer:timer=>clearTimeout(timer),
        repeat:(callback,delay)=>globalThis.setInterval(callback,delay),
        cancelRepeat:timer=>clearInterval(timer),
        getComputedStyle:element=>getComputedStyle(element),
        confirm:(...args)=>globalThis.confirm(...args),
        encodeAudio:encodeAudioDraft,
        readAudioDuration:readAudioDraftDuration,
        mediaDevices:navigator.mediaDevices,
        MediaRecorder:globalThis.MediaRecorder,
        Blob:globalThis.Blob,
        objectUrls:URL,
        location,
        now:()=>Date.now(),
        performance,
        performanceEnabled:()=>document.documentElement.dataset.nativePerformance==="1"||startupPerformanceEnabled,
        escapeSelector:value=>CSS.escape(value)
      }
    });
    if(viewName==="captures")runtime.capturesFeatureController=controller;
    return controller
  });
  descriptors.captures={root:()=>$("#view-captures"),load:()=>loadCaptureJournalPage("captures")};
  descriptors.journals={root:()=>$("#view-journals"),load:()=>loadCaptureJournalPage("journals")};
  descriptors.books={
    root:()=>$("#view-books"),
    load:()=>runtimeFeatureLoaders.library().then(module=>{
      const controller=module.createLibraryFeatureController({
        data:{
          getSnapshot:()=>state,
          getAccountId:()=>runtime.currentUser?.id||"",
          getSessionSerial:()=>sessionSerial,
          request:(url,options)=>withFeatureScope("books",()=>request(url,options)),
          requestV1:(url,options,coordination)=>featureRequestV1("books",url,options,coordination),
          refresh:(domains,options)=>refreshState(domains,options),
          applyPendingProjection,
          publish:domains=>publishDomains(new Set(domains))
        },
        navigation:{scrollTo:options=>window.scrollTo(options)},
        media:{
          validateImages:(files,maxItems)=>runPublicValidation(()=>validatedImageFiles(files,maxItems)),
          imageDataUrls,
          uploadOriginalImages:(images,idempotencyKey)=>uploadOriginalImages({request,images,idempotencyKey}),
          discardUploadedImagePath,
          readBlob:path=>apiClient.readBlob(path)
        },
        annotations:{
          rootKey:commentRootKey,
          markTarget:markCommentTarget,
          applyAnchors:applyCommentAnchors
        },
        view:{
          appUrl,
          contentState,
          escapeMarkup:escapeHtml,
          plainPreview,
          renderMarkdown,
          renderLatex,
          eventDate,
          eventTimestamp,
          formatDate,
          formatDateKey,
          formatTime,
          localDateKey,
          resetOccurrenceInput,
          occurrenceFields,
          showToast,
          entryKeyIntent
        },
        platform:{
          document,
          window,
          objectUrls:URL,
          createFile:(blob,name,type)=>new File([blob],name,{type}),
          createRequestId:()=>crypto.randomUUID(),
          requestFrame:callback=>requestAnimationFrame(callback),
          cancelFrame:frame=>cancelAnimationFrame(frame),
          getComputedStyle:element=>getComputedStyle(element),
          createRange:()=>document.createRange(),
          random:()=>Math.random(),
          confirm:(...args)=>globalThis.confirm(...args),
          escapeSelector:value=>CSS.escape(value),
          now:()=>new Date().toISOString()
        }
      });
      runtime.libraryFeatureController=controller;
      return controller
    })
  };
  descriptors.keepsakes={
    root:()=>$("#view-keepsakes"),
    load:()=>runtimeFeatureLoaders.keepsakes().then(module=>{
      const controller=module.createKeepsakeFeatureController({
        data:{
          getSnapshot:()=>state,
          getAccountId:()=>runtime.currentUser?.id||"",
          getSessionSerial:()=>sessionSerial,
          getActiveDate:()=>runtime.activeDate,
          request:(url,options)=>withFeatureScope("keepsakes",()=>request(url,options)),
          refresh:(domains,options)=>refreshState(domains,options)
        },
        media:{
          validateImages:(files,maxItems)=>runPublicValidation(()=>validatedImageFiles(files,maxItems)),
          imageDataUrls,
          readBlob:path=>apiClient.readBlob(path),
          dataUrlFromBlob
        },
        drafts:mediaDraftStore,
        navigation:{scrollTo:options=>window.scrollTo(options)},
        view:{
          appUrl,
          contentState,
          escapeMarkup:escapeHtml,
          eventTimestamp,
          eventDate,
          formatDate,
          formatDateKey,
          formatTime,
          resetOccurrenceInput,
          occurrenceFields,
          splitTags,
          formatBytes,
          feedCountLabel:(_,visible,total,unit)=>normalizedFeedSearch($("#keepsake-search")?.value)?`${visible} / ${total} ${unit}`:`${total} ${unit}`,
          feedSearchEmpty,
          localDateTimeForDate,
          setOccurrenceMode,
          showToast,
          uncertainSubmission:uncertainMediaSubmission
        },
        platform:{
          document,
          window,
          objectUrls:URL,
          IntersectionObserver:globalThis.IntersectionObserver,
          createFile:(blob,name,options)=>new File([blob],name,options),
          createRequestId:()=>crypto.randomUUID(),
          createCanvas:(width,height)=>blankCanvas(width,height),
          createImageData:(width,height,data)=>data?new ImageData(data,width,height):new ImageData(width,height),
          loadImage:loadImageSource,
          requestFrame:callback=>requestAnimationFrame(callback),
          cancelFrame:frame=>cancelAnimationFrame(frame),
          setTimer:(callback,delay)=>setTimeout(callback,delay),
          clearTimer:timer=>clearTimeout(timer),
          now:()=>Date.now(),
          confirm:(...args)=>globalThis.confirm(...args)
        }
      });
      runtime.keepsakesFeatureController=controller;
      return controller
    })
  };
  descriptors.quotes={
    root:()=>$("#view-quotes"),
    load:()=>runtimeFeatureLoaders.quotes().then(module=>{
      const controller=module.createQuotesFeatureController({
        data:{
          getSnapshot:()=>state,
          getAccountId:()=>runtime.currentUser?.id||"",
          getSessionSerial:()=>sessionSerial,
          requestV1:(url,options,coordination)=>featureRequestV1("quotes",url,options,coordination),
          refresh:(domains,options)=>refreshState(domains,options),
          applyPendingProjection,
          publish:domains=>publishDomains(new Set(domains))
        },
        annotations:{
          markTarget:markCommentTarget,
          applyAnchors:applyCommentAnchors,
          scheduleLayout:scheduleAnnotationLineCounts,
          rootKey:commentRootKey
        },
        view:{
          contentState,
          resetOccurrenceInput,
          occurrenceFields,
          showToast,
          escapeMarkup:escapeHtml
        },
        platform:{
          document,
          window,
          createRequestId:()=>crypto.randomUUID(),
          requestFrame:callback=>requestAnimationFrame(callback),
          cancelFrame:frame=>cancelAnimationFrame(frame),
          repeat:(callback,delay)=>setInterval(callback,delay),
          cancelRepeat:timer=>clearInterval(timer),
          getComputedStyle:element=>getComputedStyle(element),
          matchesMedia:query=>matchMedia(query).matches,
          confirm:(...args)=>globalThis.confirm(...args),
          performanceNow:()=>performance.now(),
          random:()=>Math.random(),
          escapeSelector:value=>CSS.escape(value)
        }
      });
      runtime.quotesFeatureController=controller;
      return controller
    })
  };
  return Object.freeze({ withCheckins });
}
